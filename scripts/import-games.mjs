// Scans public/embed/<folder>/index.html and writes src/data/imported.js with a catalog entry per folder
// that isn't already listed by hand in src/data/catalog.js. Run: npm run import-games
import fs from "node:fs"; import path from "node:path";
const root = path.resolve(import.meta.dirname, ".."), embed = path.join(root, "public/embed");
const catalogText = fs.readFileSync(path.join(root, "src/data/catalog.js"), "utf8");
const out = [], warn = [];
const esc = (s) => s.replace(/\s+/g, " ").trim();
for (const dir of fs.readdirSync(embed, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const page = path.join(embed, dir, "index.html");
  if (!fs.existsSync(page) || catalogText.includes(`/embed/${dir}/`)) continue;
  const html = fs.readFileSync(page, "utf8");
  let title = esc((html.match(/<title[^>]*>([^<]*)<\/title>/i) || [])[1] || "").split(/\s[|\-–—]\s/)[0] || dir;
  title = title.replace(/\b\w/g, (c) => c.toUpperCase()).slice(0, 40);
  const lic = fs.readdirSync(path.join(embed, dir)).find((f) => /^(licen[sc]e|copying)/i.test(f));
  if (!lic) warn.push(`${dir}: no LICENSE file found. Confirm you have the right to host it.`);
  const ext = [...new Set([...html.matchAll(/(?:src|href)=["'](https?:\/\/[^"']+)/gi)].map((m) => new URL(m[1]).host))];
  if (ext.length) warn.push(`${dir}: loads from ${ext.join(", ")}. External scripts/fonts are blocked by the server; remove them if the game is blank.`);
  const hue = [...dir].reduce((a, c) => a + c.charCodeAt(0), 0) % 360;
  out.push({ id: dir.toLowerCase().replace(/[^a-z0-9]+/g, "-"), title, category: "Arcade", src: `/embed/${dir}/index.html`, emoji: "🎮",
    accent: `hsl(${hue} 65% 45%)`, popularity: 50, added: new Date().toISOString().slice(0, 10), credit: lic ? "See license in game folder" : "", description: `Play ${title}.` });
}
fs.writeFileSync(path.join(root, "src/data/imported.js"), `// Generated by scripts/import-games.mjs. Edit categories/emoji here or move entries into catalog.js.\nexport const imported = ${JSON.stringify(out, null, 2)};\n`);
console.log(`Registered ${out.length} new game(s).`); warn.forEach((w) => console.log("  ! " + w));
